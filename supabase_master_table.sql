-- ===================================================
-- Supabase Master Table Schema (Column-Wise Format)
-- Run this script in your Supabase SQL Editor
-- ===================================================

DROP TABLE IF EXISTS public.master CASCADE;

CREATE TABLE public.master (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indentor_name TEXT,
    authorized_name TEXT,
    machine_name TEXT,
    department TEXT,
    uom TEXT,
    firm_name TEXT,
    payment_type TEXT,
    type_of_bill TEXT,
    vendor_name TEXT,
    transporter_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.master ENABLE ROW LEVEL SECURITY;

-- Allow public read & write access
CREATE POLICY "Allow public read master" ON public.master
    FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "Allow public insert master" ON public.master
    FOR INSERT TO anon, authenticated WITH CHECK (true);

CREATE POLICY "Allow public update master" ON public.master
    FOR UPDATE TO anon, authenticated USING (true);

CREATE POLICY "Allow public delete master" ON public.master
    FOR DELETE TO anon, authenticated USING (true);
